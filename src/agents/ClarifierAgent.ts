import { Agent } from '@/workflow/engine/Agent';
import { WorkflowContext } from '@/workflow/engine/WorkflowContext';
import { gateway } from '@/ai/gateway/gateway';
import { ClarifierOutput, ClarifierOutputSchema } from '@/ai/schemas/clarifierSchema';
import { PromptRegistry } from '@/ai/prompts/registry';

export class ClarifierAgent implements Agent<ClarifierOutput> {
  capability = 'clarify';
  name = 'Clarifying';

  async execute(ctx: WorkflowContext): Promise<ClarifierOutput> {
    const prompt = `
Review the implementation plan and identify missing assumptions or clarifying questions.

### Idea
${ctx.input.rawIdea}

### Plan
${JSON.stringify(ctx.artifacts.planning, null, 2)}
`;
    
    try {
      const { object } = await gateway.executeObject({
        capability: this.capability as any,
        system: await PromptRegistry.clarify(),
        prompt,
        schema: ClarifierOutputSchema,
      });
      return object;
    } catch (e) {
      console.error("ClarifierAgent LLM execution failed, using fallback:", e);
      return {
        assumptions: [
          {
            assumption: "The user has required infrastructure set up.",
            traceability: {
              derivedFrom: ctx.input.rawIdea || "raw idea",
              reason: "Fallback assumption due to LLM unavailability.",
              confidence: 50,
              sourceComponent: "System Default",
            }
          }
        ],
        questions: [
          {
            question: "Did the LLM generation fail, meaning you are seeing fallback rules?",
            category: "Technical constraints",
            options: [
              { label: "Yes, use defaults", value: "yes" },
              { label: "No", value: "no" }
            ],
            rationale: "LLM services are currently unavailable.",
            traceability: {
              derivedFrom: ctx.input.rawIdea || "raw idea",
              reason: "Generated by rule-based fallback.",
              confidence: 50,
              sourceComponent: "System Default",
            }
          }
        ],
        confidenceScore: 50,
        ambiguityScore: 50
      };
    }
  }
}
