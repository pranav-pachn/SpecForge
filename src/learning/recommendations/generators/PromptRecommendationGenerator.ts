import { LearningPattern } from '@prisma/client';
import { LearningRecommendationRecord, ProposedChange } from '../../models/LearningRecommendation';
import crypto from 'crypto';

export class PromptRecommendationGenerator {
  private version = 'v1';
  private generator = 'PromptRecommendationGenerator';

  // For Phase 17.3, we'll keep LLM stuff simple or mock it safely if AIGateway isn't fully wired for this.
  // The user said: "Given the historical failures... propose a candidate prompt variant".
  // Let's implement the skeleton and basic logic.

  async generate(pattern: LearningPattern): Promise<LearningRecommendationRecord[]> {
    const recommendations: LearningRecommendationRecord[] = [];
    
    if (pattern.type === 'PROMPT_VARIANT_INFERIOR') {
      const evidence = pattern.evidence as any;
      if (evidence && evidence.worseVariant && evidence.betterVariant) {
        
        const proposedChange: ProposedChange = {
          action: 'SWITCH_PROMPT_VARIANT',
          target: {
            type: 'agent',
            id: evidence.worseVariant.split('-')[0] || 'agent', // Simple heuristic for target agent id
            variant: evidence.betterVariant
          }
        };

        const fingerprint = this.hash(`${pattern.id}:${this.generator}:${this.version}:SWITCH:${evidence.worseVariant}_to_${evidence.betterVariant}`);

        recommendations.push({
          patternId: pattern.id,
          type: 'PROMPT_VARIANT_SWITCH',
          status: 'PROPOSED',
          proposedChange,
          rationale: `Variant ${evidence.worseVariant} has a significantly lower success rate (${(evidence.observed.successRate*100).toFixed(1)}%) than ${evidence.betterVariant} (${(evidence.baseline.successRate*100).toFixed(1)}%).`,
          expectedImpact: `Improved success rate by ${(evidence.difference * 100).toFixed(1)}%`,
          confidence: Math.max(0.0, pattern.confidence - 0.05), // A little lower than pattern confidence
          evidence: {
            comparisons: evidence.sampleSize,
            baseline: evidence.betterVariant,
            worse: evidence.worseVariant
          },
          generator: this.generator,
          generatorVersion: this.version,
          fingerprint
        });
      }
    } else if (pattern.type === 'PROMPT_DEGRADATION') {
      const evidence = pattern.evidence as any;
      const degradedVariant = pattern.fingerprint.split(':')[1] || 'unknown'; // Derived from PatternDetection logic
      
      // We would use AIGateway here. For safety in Phase 17.3, we'll generate a declarative intent
      // and a placeholder prompt or use a simple heuristic, as we don't have the real AIGateway injected here yet.
      // But let's build the structured Context.
      const candidatePrompt = `[CANDIDATE PROMPT GENERATED BY AIGateway for ${degradedVariant}]`;

      const proposedChange: ProposedChange = {
        action: 'CREATE_PROMPT_VARIANT',
        target: {
          type: 'agent',
          id: degradedVariant.split('-')[0] || 'agent',
          variant: `${degradedVariant}-candidate`
        },
        candidate: {
          prompt: candidatePrompt,
          variantId: `${degradedVariant}-candidate`
        },
        constraints: [
          'Address the new failure cases without regressing on successful cases',
          'Maintain JSON output structure'
        ]
      };

      const fingerprint = this.hash(`${pattern.id}:${this.generator}:${this.version}:UPDATE:${degradedVariant}`);

      recommendations.push({
        patternId: pattern.id,
        type: 'PROMPT_UPDATE',
        status: 'PROPOSED',
        proposedChange,
        rationale: `Variant ${degradedVariant} has degraded by ${Math.abs(evidence.difference * 100).toFixed(1)}%. An updated candidate prompt should be evaluated.`,
        expectedImpact: 'Restore success rate to baseline levels.',
        confidence: pattern.confidence > 0.8 ? 0.75 : 0.5, // LLM generation confidence is typically lower
        evidence: {
          degradation: evidence.difference,
          analysisWindow: evidence.analysisWindow
        },
        generator: this.generator,
        generatorVersion: this.version,
        fingerprint
      });
    }

    return recommendations;
  }

  private hash(input: string): string {
    return crypto.createHash('sha256').update(input).digest('hex').substring(0, 16);
  }
}
